#!/usr/bin/env python3
"""
Wrapper for lmkgs.py that supports custom datasets via stats JSON files.

Dataset parameters (d, b, n, e) are read directly from the stats JSON file
(generated by fice-to-lmkg.py or prepare-mega-graph.py) located at
LMKG-Code/lmkg-s/statistics/<dataset>_stats.json.

Usage examples:
  # Training
  python benchmarks/lmkg/run-lmkgs.py --training --dataset mega_no_lubm \\
      --query-type combined --query-join 2 --epochs 100 --batch-size 512

  # Evaluation
  python benchmarks/lmkg/run-lmkgs.py --eval --dataset mega_no_lubm \\
      --query-type combined --query-join 2 --test-mode all

All extra flags are forwarded to lmkgs.py unchanged.
"""

import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent
LMKG_S_DIR = PROJECT_ROOT / "benchmarks/lmkg/LMKG-Code/lmkg-s"


def get_dataset_name(argv):
    """Extract --dataset value from the argument list."""
    for i, arg in enumerate(argv):
        if arg == "--dataset" and i + 1 < len(argv):
            return argv[i + 1]
    return None


def run_lmkgs(args):
    """Run lmkgs.py with the given argument list.

    Returns the subprocess exit code.
    """
    dataset_name = get_dataset_name(args)
    if dataset_name is None:
        print("ERROR: --dataset not found in arguments", file=sys.stderr)
        return 1

    lmkgs_path = LMKG_S_DIR / "lmkgs.py"
    result = subprocess.run(
        [sys.executable, str(lmkgs_path)] + args,
        cwd=LMKG_S_DIR,
    )
    return result.returncode


def main():
    # Pass all arguments after the script name directly to lmkgs.py
    args = sys.argv[1:]
    if not args:
        print(__doc__)
        sys.exit(0)

    exit_code = run_lmkgs(args)
    sys.exit(exit_code)


if __name__ == "__main__":
    main()
